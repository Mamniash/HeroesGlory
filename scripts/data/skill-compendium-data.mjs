/**
 * @returns {object[]} finished compendium Item documents, book order (1-20, 20А, 20Б).
 */
export function buildSkillDocuments() {
  return SKILLS.map((skill, index) => buildItemDocument({
    name: skill.name,
    type: 'skill',
    // Real per-skill art (base-tier frame) rather than a generic icon —
    // the hero sheet re-derives its own icon from skillKey+tier at
    // render time (secondarySkillIconPath in hero-sheet.mjs) regardless
    // of this field, so this only matters for the compendium listing and
    // the item sheet header, but there's no reason to settle for less
    // when the art already exists.
    img: secondarySkillIconPath(skill.key, 'base', { large: true }),
    system: {
      skillKey: skill.key,
      tier: 'base',
      effects: { base: skill.base, advanced: skill.advanced, expert: skill.expert },
    },
    index,
  }));
}
